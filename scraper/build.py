def run(output=None):
    out = Path(output) if output else OUT_HTML
    with open(SRC_JSON, encoding="utf-8") as f:
        data = json.load(f)
    meds = data.get("medicines", [])
    updated = data.get("updated_at", "")
    try:
        dt = datetime.fromisoformat(updated.replace("Z", "+00:00"))
        updated_str = dt.strftime("%Y年%m月%d日 更新")
    except Exception:
        updated_str = ""

    meds_js  = json.dumps(meds,        ensure_ascii=False).replace("</script>", "<\\/script>")
    ing_js   = json.dumps(ING_DICT,    ensure_ascii=False).replace("</script>", "<\\/script>")
    col_js   = json.dumps(COLUMNS,     ensure_ascii=False).replace("</script>", "<\\/script>")
    sym_js   = json.dumps(SYMP_GROUPS, ensure_ascii=False).replace("</script>", "<\\/script>")
    cats_js  = json.dumps(CATS,        ensure_ascii=False).replace("</script>", "<\\/script>")

    print(f"[build] {len(meds)}件 → {out}")

    css   = open(DATA_DIR / "tmpl_css.css",  encoding="utf-8").read()
    js    = open(DATA_DIR / "tmpl_js.js",    encoding="utf-8").read()
    body  = open(DATA_DIR / "tmpl_body.html",encoding="utf-8").read()

    js = js.replace("__MEDS__",  meds_js).replace("__ING__",   ing_js)\
           .replace("__COLS__",  col_js).replace("__SYMS__", sym_js)\
           .replace("__CATS__",  cats_js)
    body = body.replace("__UPDATED__", updated_str).replace("__COUNT__", str(len(meds)))

    html = f"""<!DOCTYPE html>
<html lang="ja">
<head>
<meta charset="UTF-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>くすり成分ガイド｜OTC医薬品データベース</title>
<meta name="description" content="市販薬を成分から比較。リスク区分・眠気・要注意成分を確認。{len(meds)}品目収録。">
<style>{css}</style>
</head>
<body>
{body}
<script>{js}</script>
</body>
</html>"""

    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(html, encoding="utf-8")
    print(f"[build] 完了 {out.stat().st_size:,} bytes")

if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--output", default=str(OUT_HTML))
    a = p.parse_args()
    run(output=a.output)
